class StudySession:
    """Interactive study session with unified navigation and DeepSeek API grading.

    Navigation keys (work across all phases):
        [P]         - Go back to previous item
        [N] / Enter - Next item
        [Q]         - Quit and show summary
        [1]         - Mark as mastered (knowledge points)
        [2]         - Mark as needs review (knowledge points)
        [3]         - Show explanation / reference answer
        [0]         - Skip
    """

    def __init__(self, knowledge_points=None, questions=None, case_study=None,
                 api_key=None, progress_data=None, progress_path=None):
        self.knowledge_points = knowledge_points or []
        self.questions = questions or []
        self.case_study = case_study
        self.api_key = api_key or DEEPSEEK_API_KEY
        # 学习进度: progress_data 为 dict, 答题时自动记录; None 则不记录
        self.progress_data = progress_data
        self.progress_path = progress_path or progress_store.PROGRESS_PATH

        # Build unified item list for seamless [P] navigation across phases
        self.items = []
        for kp in self.knowledge_points:
            self.items.append(("knowledge_point", kp))
        for q in self.questions:
            self.items.append(("question", q))
        if self.case_study:
            self.items.append(("case_study", self.case_study))

        self.idx = 0
        self.results = {
            "kp_total": 0, "kp_mastered": 0, "kp_review": 0, "kp_skipped": 0,
            "q_total": 0, "q_correct": 0, "q_wrong": 0, "q_skipped": 0,
            "sa_scores": [],
        }

    # ------------------------------------------------------------------
    # Progress Recording
    # ------------------------------------------------------------------

    def _record(self, q_id, correct, user_input=None, ai_output=None):
        """记录一次答题结果到进度数据(若启用)。"""
        if self.progress_data is None:
            return
        try:
            progress_store.record_answer(
                self.progress_data, q_id, correct,
                user_input=user_input, ai_output=ai_output)
        except Exception:
            pass

    def _save_progress(self):
        """保存进度数据(若启用)。"""
        if self.progress_data is None:
            return
        try:
            progress_store.save_progress(self.progress_data, path=self.progress_path)
        except Exception:
            pass

    # ------------------------------------------------------------------
    # DeepSeek API Grading
    # ------------------------------------------------------------------

    def grade_with_deepseek(self, question, user_answer, reference_answer,
                            scoring_points):
        """Grade a short-answer response using DeepSeek API.

        Returns dict with keys: score (int 0-10), reason (str),
        suggestion (str, non-empty if score < 8).
        Returns None on error or if API key is not configured.
        """
        if not self.api_key:
            print("  [!] 未配置 DeepSeek API Key，跳过AI评分。")
            print("  [!] 请在脚本中填写 DEEPSEEK_API_KEY 或在 esg_engine.py 中配置。")
            print("  [!] 获取地址: https://platform.deepseek.com/")
            return None

        try:
            from openai import OpenAI
        except ImportError:
            print("  [!] 未安装 openai 包，请运行: pip install openai")
            return None

        try:
            client = OpenAI(api_key=self.api_key, base_url=DEEPSEEK_BASE_URL)

            # 系统提示词: 完全使用项目数据审计掩护语, 不出现"考试/考生/答题"等表述
            system_prompt = (
                "你是一位项目数据质量评估专家，负责评审用户提交的数据样本是否符合标准数据规范。"
                "请使用项目审计语言描述评估结果（如『该数据项的覆盖/数据样本的完整性/标准的符合程度』等），"
                "不要使用考试、考生、答题等表述。\n\n"
                "评分标准：\n"
                "- 满分10分\n"
                "- 根据评估要点的覆盖程度打分\n"
                "- 内容准确性、完整性、逻辑性\n"
                "- 表述清晰、条理分明可酌情加分\n\n"
                "请严格按照以下JSON格式输出：\n"
                "{\n"
                '  "score": 8,\n'
                '  "reason": "评估理由(项目语言), 指出符合和遗漏的要点",\n'
                '  "suggestion": "得分<8时给出改进建议；得分>=8时为空字符串"\n'
                "}\n\n"
                "示例：\n"
                '{"score": 7, "reason": "数据样本涵盖了E和S的要点，但G的数据描述不够完整, '
                '缺少信息披露和治理结构方面的内容", "suggestion": "建议补充G(治理)方面关于'
                '信息披露和治理结构的内容"}'
            )

            # 用户提示词: 同样用掩护语术语
            user_prompt = (
                f"数据项描述: {question}\n\n"
                f"标准数据: {reference_answer}\n\n"
                f"评估要点: {json.dumps(scoring_points, ensure_ascii=False)}\n\n"
                f"用户提交的样本: {user_answer}"
            )

            response = client.chat.completions.create(
                model=DEEPSEEK_MODEL,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                response_format={"type": "json_object"},
                max_tokens=1000,
            )

            content = response.choices[0].message.content
            result = json.loads(content)

            # Validate structure
            score = int(result.get("score", 0))
            score = max(0, min(10, score))  # Clamp 0-10
            reason = result.get("reason", "")
            suggestion = result.get("suggestion", "")

            return {"score": score, "reason": reason, "suggestion": suggestion}

        except json.JSONDecodeError:
            print("  [!] API返回格式异常，请对照标准数据自行判断。")
            return None
        except Exception as e:
            error_msg = str(e)
            if "401" in error_msg or "authentication" in error_msg.lower():
                print("  [!] API Key 无效，请检查配置。")
            elif "rate_limit" in error_msg.lower() or "429" in error_msg:
                print("  [!] API调用频率超限，请稍后重试。")
            elif "connection" in error_msg.lower() or "timeout" in error_msg.lower():
                print("  [!] 网络连接异常，请检查网络后重试。")
            else:
                print(f"  [!] API错误: {error_msg[:120]}")
            return None

