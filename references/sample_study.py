SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

def load_json(filename):
    """Load JSON from the script's directory."""
    path = os.path.join(SCRIPT_DIR, filename)
    if not os.path.exists(path):
        print(f"  [!] File not found: {path}")
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def select_knowledge_points(kb_data, count=10):
    """Select knowledge points, rotating based on today's date.

    Each day covers different knowledge points, cycling through all 74 over
    approximately 8 days.
    """
    all_kps = kb_data.get("knowledge_points", [])
    if not all_kps:
        return []

    today = datetime.date.today()
    day_offset = today.toordinal() % max(1, len(all_kps))

    # Rotate starting point each day, select 'count' items
    selected = []
    for i in range(count):
        idx = (day_offset + i) % len(all_kps)
        selected.append(all_kps[idx])
    return selected


def select_questions(qb_data, count=10, kp_refs=None, progress_data=None, exclude=None):
    """Select questions by learning progress: unanswered first, then low-accuracy,
    then least-practiced. Falls back to balanced type mix.
    """
    import random
    all_qs = qb_data.get("questions", [])
    if not all_qs:
        return []

    today = datetime.date.today()
    random.seed(today.toordinal())

    # Progress-aware selection (when progress data exists)
    if progress_data is not None:
        try:
            import progress_store
            selected = progress_store.select_questions(
                progress_data, all_qs, count, exclude=exclude or set())
            if len(selected) >= count:
                return selected[:count]
        except Exception:
            pass

    # Fallback: balanced type mix (original behavior)
    by_type = {}
    for q in all_qs:
        t = q["type"]
        if t not in by_type:
            by_type[t] = []
        by_type[t].append(q)

    per_type = max(1, count // 4)
    remainder = count - per_type * 4

    selected = []
    for qtype in ["single_choice", "multiple_choice", "true_false", "short_answer"]:
        pool = by_type.get(qtype, [])
        random.shuffle(pool)

        if kp_refs:
            linked = [q for q in pool if q.get("kp_ref") in kp_refs]
            others = [q for q in pool if q.get("kp_ref") not in kp_refs]
            pick = linked + others
        else:
            pick = pool

        n = per_type + (1 if remainder > 0 else 0)
        remainder -= 1
        selected.extend(pick[:n])

    return selected[:count]


