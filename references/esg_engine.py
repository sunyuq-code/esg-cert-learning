def normalize_answer(answer):
    """Normalize answer to uppercase string for comparison.

    Handles: "ABC", ["A","B","C"], "A,B,C", "abc" -> "ABC"
    Choice answers are sorted for consistent comparison ("BAC" -> "ABC");
    non-choice strings (e.g. "True") are uppercased but NOT sorted.
    """
    if isinstance(answer, list):
        return "".join(sorted(a.upper().strip() for a in answer))
    if isinstance(answer, str):
        # Remove commas, spaces, and uppercase
        cleaned = answer.replace(",", "").replace(" ", "").upper()
        # Only sort multi-letter answers that are pure choice letters (A-E)
        if len(cleaned) > 1 and all(c in "ABCDE" for c in cleaned):
            return "".join(sorted(cleaned))
        return cleaned
    return str(answer).upper().strip()


