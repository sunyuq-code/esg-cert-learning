def main():
    mode = "full"
    if len(sys.argv) > 1:
        mode = sys.argv[1].lower()

    # Import the engine
    sys.path.insert(0, SCRIPT_DIR)
    from esg_engine import StudySession

    # Load data
    kb_data = load_json("knowledge_base.json")
    qb_data = load_json("question_bank.json")

    if not qb_data:
        print("Cannot find question_bank.json. Make sure it's in the same directory.")
        sys.exit(1)

    # Load learning progress (用于智能选题与记录)
    try:
        import progress_store
        progress_data = progress_store.load_progress()
    except Exception:
        progress_data = None

    # Select content based on mode
    knowledge_points = []
    questions = []
    case_study = None
    session_exclude = set()  # 本会话已用题目(避免重复)

    if mode in ("full", "review"):
        kp_count = 10 if mode == "full" else 15
        knowledge_points = select_knowledge_points(kb_data or {}, count=kp_count)
        print(f"  Selected {len(knowledge_points)} knowledge points")

    if mode in ("full", "quiz"):
        kp_refs = set(kp["id"] for kp in knowledge_points) if knowledge_points else None
        questions = select_questions(qb_data, count=10, kp_refs=kp_refs,
                                     progress_data=progress_data, exclude=session_exclude)
        session_exclude.update(q["id"] for q in questions)
        print(f"  Selected {len(questions)} questions (progress-aware)")

    if mode in ("full", "case"):
        case_study = CASE_STUDY

    if mode == "review" and not knowledge_points:
        print("No knowledge points available.")
        sys.exit(1)
    if mode == "quiz" and not questions:
        print("No questions available.")
        sys.exit(1)

    # Create and run session (进度记录开启)
    session = StudySession(
        knowledge_points=knowledge_points,
        questions=questions,
        case_study=case_study,
        api_key=DEEPSEEK_API_KEY,
        progress_data=progress_data,
    )
    session.run()


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n\n  [Interrupted] Session data saved.")
        sys.exit(0)
