def load_question_bank(bank_path=None):
    """Load the full question bank from JSON file.

    Returns a dict: {kp_id: [questions for that KP], ...}
    Also returns a flat list of all questions.
    """
    if bank_path is None:
        # Try default location relative to this file
        bank_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                 "question_bank.json")
    if not os.path.exists(bank_path):
        print(f"  [!] Question bank not found at: {bank_path}")
        return {}, []

    with open(bank_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    questions = data.get("questions", [])
    by_kp = {}
    for q in questions:
        kp = q.get("kp_ref", "unknown")
        if kp not in by_kp:
            by_kp[kp] = []
        by_kp[kp].append(q)

    return by_kp, questions


def load_knowledge_base(kb_path=None):
    """Load knowledge points from the knowledge base JSON.

    The knowledge base is expected as a JSON file with a list of knowledge
    point dicts. If the file doesn't exist, returns empty list.
    """
    if kb_path is None:
        kb_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                               "knowledge_base.json")
    if not os.path.exists(kb_path):
        return []

    with open(kb_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, list):
        return data
    return data.get("knowledge_points", data.get("items", []))


